// Generates supabase/migrations/20261030000004_seed_content.sql from the
// Markdown files in content/ and content/faqs.json.
//
// Run with:  node scripts/build-content-migration.mjs
//
// The migration only INSERTS content that does not exist yet, so it never
// overwrites text the owner has already edited in the admin dashboard.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname;

function parse(file) {
  const raw = readFileSync(file, 'utf8');
  const m = raw.match(/^---\ntitle: (.+)\n---\n([\s\S]*)$/);
  if (!m) throw new Error(`Missing front matter in ${file}`);
  return { title: m[1].trim(), body: m[2].trim() + '\n' };
}

// Dollar-quote a string safely for SQL.
function dq(text) {
  let tag = 'c';
  while (text.includes(`$${tag}$`)) tag += 'c';
  return `$${tag}$${text}$${tag}$`;
}

const rows = [];
for (const [dir, isLegal] of [['pages', false], ['legal', true]]) {
  for (const f of readdirSync(join(root, 'content', dir)).sort()) {
    if (!f.endsWith('.md')) continue;
    const { title, body } = parse(join(root, 'content', dir, f));
    rows.push(`  (${dq(f.replace(/\.md$/, ''))}, ${dq(title)}, ${dq(body)}, ${isLegal}, ${isLegal})`);
  }
}

const faqs = JSON.parse(readFileSync(join(root, 'content', 'faqs.json'), 'utf8'));
const faqRows = faqs.map((f, i) => `  (${dq(f.q)}, ${dq(f.a)}, ${(i + 1) * 10})`);

const sql = `-- Generated by scripts/build-content-migration.mjs — edit content/ and re-run.
-- Seeds editable website text, legal drafts and FAQs. Existing rows are kept.

insert into public.site_content (key, title, body, is_legal, is_draft) values
${rows.join(',\n')}
on conflict (key) do nothing;

insert into public.faqs (question, answer, sort_order)
select v.question, v.answer, v.sort_order from (values
${faqRows.join(',\n')}
) as v (question, answer, sort_order)
where not exists (select 1 from public.faqs);
`;
writeFileSync(join(root, 'supabase', 'migrations', '20261030000004_seed_content.sql'), sql);
console.log(`Wrote ${rows.length} content rows and ${faqs.length} FAQs.`);
